CREATE TABLE entrega (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    disciplina_id BIGINT       NOT NULL,
    titulo        VARCHAR(120) NOT NULL,
    descricao     TEXT,
    tipo          VARCHAR(50)  NOT NULL,
    prazo         TIMESTAMP    NOT NULL,
    CONSTRAINT fk_entrega_disciplina
        FOREIGN KEY (disciplina_id) REFERENCES disciplina (id) ON DELETE CASCADE
);

CREATE TABLE progresso_atividade (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aluno_id       BIGINT      NOT NULL,
    entrega_id     BIGINT      NOT NULL,
    status         VARCHAR(50) NOT NULL,
    data_conclusao TIMESTAMP,
    CONSTRAINT fk_progresso_aluno
        FOREIGN KEY (aluno_id) REFERENCES aluno (id) ON DELETE CASCADE,
    CONSTRAINT fk_progresso_entrega
        FOREIGN KEY (entrega_id) REFERENCES entrega (id) ON DELETE CASCADE,
    CONSTRAINT uk_progresso_aluno_entrega UNIQUE (aluno_id, entrega_id)
);

CREATE INDEX idx_entrega_disciplina ON entrega (disciplina_id);