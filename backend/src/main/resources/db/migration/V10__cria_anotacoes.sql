CREATE TABLE anotacao (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aluno_id      BIGINT       NOT NULL,
    disciplina_id BIGINT       NOT NULL,
    titulo        VARCHAR(120) NOT NULL,
    texto         TEXT         NOT NULL,
    data_criacao  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_anotacao_aluno
        FOREIGN KEY (aluno_id) REFERENCES aluno (id) ON DELETE CASCADE,
    CONSTRAINT fk_anotacao_disciplina
        FOREIGN KEY (disciplina_id) REFERENCES disciplina (id) ON DELETE CASCADE
);

CREATE INDEX idx_anotacao_aluno_data
    ON anotacao (aluno_id, data_criacao DESC);

CREATE INDEX idx_anotacao_aluno_disciplina_data
    ON anotacao (aluno_id, disciplina_id, data_criacao DESC);
