-- Tabelas base do Cancha (Documento de Arquitetura, Figura 2).
-- Usuario e a raiz da hierarquia; cada perfil tem a sua tabela filha (heranca por juncao).
-- Por enquanto so existe o perfil Aluno; Representante Escolar e Administrador entram
-- com as suas proprias migrations quando forem implementados.

CREATE TABLE usuario (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    papel       VARCHAR(30)  NOT NULL,
    nome        VARCHAR(120) NOT NULL,
    email       VARCHAR(160) NOT NULL,
    senha_hash  VARCHAR(100) NOT NULL,
    CONSTRAINT uk_usuario_email UNIQUE (email),
    CONSTRAINT ck_usuario_papel
        CHECK (papel IN ('ALUNO', 'REPRESENTANTE_ESCOLAR', 'ADMINISTRADOR_SISTEMA'))
);

CREATE TABLE aluno (
    id             BIGINT      PRIMARY KEY,
    matricula_unb  VARCHAR(20) NOT NULL,
    CONSTRAINT uk_aluno_matricula_unb UNIQUE (matricula_unb),
    CONSTRAINT fk_aluno_usuario
        FOREIGN KEY (id) REFERENCES usuario (id) ON DELETE CASCADE
);

CREATE TABLE disciplina (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome            VARCHAR(120) NOT NULL,
    periodo_letivo  VARCHAR(10)  NOT NULL,
    CONSTRAINT uk_disciplina_nome_periodo UNIQUE (nome, periodo_letivo)
);

CREATE TABLE matricula (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aluno_id              BIGINT           NOT NULL,
    disciplina_id         BIGINT           NOT NULL,
    progresso_percentual  DOUBLE PRECISION NOT NULL DEFAULT 0,
    data_matricula        DATE             NOT NULL,
    CONSTRAINT fk_matricula_aluno
        FOREIGN KEY (aluno_id) REFERENCES aluno (id) ON DELETE CASCADE,
    CONSTRAINT fk_matricula_disciplina
        FOREIGN KEY (disciplina_id) REFERENCES disciplina (id) ON DELETE CASCADE,
    CONSTRAINT uk_matricula_aluno_disciplina UNIQUE (aluno_id, disciplina_id),
    CONSTRAINT ck_matricula_progresso
        CHECK (progresso_percentual BETWEEN 0 AND 100)
);

CREATE INDEX idx_matricula_disciplina ON matricula (disciplina_id);
